"""Product Brain packets rendered from the real Product Brain templates (Plan 5, reference/product-brain).

Unknown fields stay as {{placeholder}}, the marker Product Brain's backend counts as empty, so
`wow pack check` predicts the completion before pasting. Packet text is Spanish (pasted into Product Brain).
"""
from __future__ import annotations

import re
from datetime import date
from pathlib import Path
from typing import Dict, List, Optional

import pbcompletion
import pbtemplate

UNDEFINED = "[SIN DEFINIR]"
_BRIEF_KEYS = ("Goal", "Problem", "Decisions", "Constraints", "Non-goals", "Open questions")
_BULLET_RE = re.compile(r"^\s*-\s*([A-Za-z -]+?):\s*(.*)$")

PREAMBLE = """Reglas para este documento (aplicalas en todas las secciones):
1. Usá solo la información de este chat y de los documentos que adjunto. Si un dato no está,
   escribí [SIN DEFINIR] y agregalo a "Preguntas abiertas". No lo completes con ejemplos genéricos ni con TODO.
2. Conservá las etiquetas [MEDIDO], [ESTIMACIÓN] y [SIN DEFINIR] tal como vienen.
3. Las filas de la plantilla pensadas para un marketplace (comprador, vendedor) se completan con
   "No aplica: <motivo>" si este dominio no las tiene; no adaptes el dominio a la plantilla.
4. Las secciones "API Gateway" y "SLA" se completan con la verdad: "No aplica: <motivo>" o [SIN DEFINIR].
   No agregues componentes, proveedores, SLAs, circuit breakers, North Star con targets, plazos ni owners
   que no figuren en el material.
5. Las decisiones pendientes del owner van a "Preguntas abiertas", no se resuelven por inferencia.
   En cada fila, Owner es el rol que decide (no inventes personas) y Estado es "Abierta".
6. Conservá los ids de los criterios (AC1, E1.C1…) tal como vienen.
7. Antes de dar una sección por completa, listá las afirmaciones que no tienen fuente en el material.
   No marques un ítem del checklist como cumplido sin citar dónde se cumple.
"""

OWNER_ROLE = "Owner de producto"
# Registro packets: Product Brain records the work, it does not plan it. Every field the plan does not orient
# carries this explicit marker, which Product Brain's backend counts as filled.
REGISTRO_REASON = "registro de la iniciativa; el plan y el detalle viven en el repo y en Spec-Kit."
NA = "No aplica"
# Context-pack claim ids (C14) and decision ids (D2) are internal: Product Brain copies them into Jira.
# Only the shapes wow writes are references: "(C3)", "(C4, C5)", "(medido, C8)" and the "D1 " that opens a
# decision. A bare "D7" or "C4" in prose is content (retention D7, the C4 model) and stays.
_REF_GROUP_RE = re.compile(r"\s*\((?:[CD]\d+)(?:\s*[,;]\s*[CD]\d+)*\)")
_REF_TAIL_RE = re.compile(r"(?:\s*[,;]\s*[CD]\d+)+(?=\s*\))")
_DECISION_ID_RE = re.compile(r"^D\d+\s+")
_TASK_REF_RE = re.compile(r"\s*\(tareas? [\d., y]+\)")
# Product Brain only registers: commits are internal evidence (they stay in wow/). A pasted GitHub URL opens its file
# picker and drops the whole text (chat-composer.tsx:198-207); a bare SHA is resolved against a single repo.
_GITHUB_URL_RE = re.compile(r"https?://(?:www\.)?github\.com/[\w.-]+/([\w.-]+)(?:/[^\s)\]]*)?")
_AT_SHA_RE = re.compile(r"\s*@\s*[0-9a-f]{7,40}\b")
_LIST_COMMA_RE = re.compile(r"(?<!\d),|,(?!\d)")  # decimal commas (1,5 s) are not separators
INITIATIVE_TYPE = {"brownfield": "Evolución de sistema existente", "greenfield": "Iniciativa nueva"}
PRIORITY_ES = {"high": "Alta", "medium": "Media", "low": "Baja"}
_NONE = ("", "none", "ninguna", "ninguno")


def _header(mhash: str, command: str) -> str:
    return f"<!-- wow: manifest-hash={mhash} template={pbtemplate.TEMPLATE_ID} · generated by `{command}` -->"


def _items(value: str) -> List[str]:
    parts = [p.strip() for p in re.split(r"[·;]", value or "")]
    return [p for p in parts if p.lower() not in _NONE]


def strip_refs(text: str) -> str:
    text = _AT_SHA_RE.sub("", _GITHUB_URL_RE.sub(lambda m: m.group(1), text))
    return _REF_TAIL_RE.sub("", _TASK_REF_RE.sub("", _REF_GROUP_RE.sub("", text)))


def _pb(text: str) -> str:
    """Packet body as Product Brain receives it: no internal references; the wow header comment is kept."""
    header, _, body = text.partition("\n")
    return header + "\n" + "\n".join(strip_refs(line) for line in body.split("\n"))


def _list_item(value: str) -> str:
    # Product Brain splits list items on commas: one item with a comma becomes two broken bullets.
    return _LIST_COMMA_RE.sub(";", strip_refs(_cell(value)))


def _cell(value: str) -> str:
    """Table cells and list items stay on one line, and a literal pipe cannot add a column."""
    return re.sub(r"\s*\n\s*", " ", str(value)).replace("|", "\\|")


def _sub(text: str, values: Dict[str, str]) -> str:
    for name, value in values.items():
        text = re.sub(r"\{\{\s*" + re.escape(name) + r"\s*\}\}", lambda _m, v=value: v, text)
    return text


def _rows(text: str, prefix: str, items: List[Dict[str, str]]) -> str:
    """Replace the template rows of a numbered group with one row per item; unknown cells keep a placeholder."""
    if not items:
        return text
    pattern = re.compile(r"\{\{\s*" + re.escape(prefix) + r"_(\d+)(?:_([a-z0-9_]+))?\s*\}\}")
    lines = text.split("\n")
    positions = [i for i, line in enumerate(lines) if pattern.search(line)]
    if not positions:
        return text
    template_row = lines[positions[0]]
    rows = []
    for n, item in enumerate(items, 1):
        def cell(match, n=n, item=item):
            sub = match.group(2) or ""
            return _cell(item[sub]) if item.get(sub) else "{{%s_%d%s}}" % (prefix, n, f"_{sub}" if sub else "")
        rows.append(re.sub(r"^\|\s*1\s*\|", f"| {n} |", pattern.sub(cell, template_row)))
    return "\n".join(lines[:positions[0]] + rows + lines[positions[-1] + 1:])


def _open_questions(brief: Dict[str, str], pending, owner_role: str) -> Optional[str]:
    questions = _items(brief["Open questions"]) + list(pending)
    if questions:
        return "\n".join(f"| {n} | {q} | {owner_role} | Abierta |" for n, q in enumerate(questions, 1))
    if brief["Open questions"].strip().lower() in _NONE[1:]:
        return f"| 1 | Ninguna | {owner_role} | Cerrada |"
    return None


def _quarter(today: date) -> str:
    return f"Q{(today.month - 1) // 3 + 1}/{today.year}"


def _registro(text: str, kind: str) -> str:
    """Collapse every unused numbered group to one row and mark every remaining placeholder."""
    _, groups = pbtemplate.units(kind)
    for prefix, group in groups.items():
        rows = [line for line in text.split("\n") if re.search(r"\{\{\s*" + re.escape(prefix) + r"_\d", line)]
        # Only a group the renderer left untouched collapses; a populated one keeps every row.
        if group["index_type"] == "numeric" and rows and all(_template_only(row) for row in rows):
            text = _rows(text, prefix, [{}])
    text = text.replace("{{open_questions}}", f"| 1 | Ninguna | {OWNER_ROLE} | Cerrada |")
    lines = []
    for line in text.split("\n"):
        short = line.lstrip().startswith(("|", "#")) or "`{{" in line
        lines.append(_DOUBLE_RE.sub(NA if short else f"{NA}: {REGISTRO_REASON}", line) if "{{" in line else line)
    return "\n".join(lines)


_DOUBLE_RE = re.compile(r"\{\{\s*[a-zA-Z0-9_.-]+\s*\}\}")


def _template_only(line: str) -> bool:
    return not re.sub(r"[\s|\-\d]", "", _DOUBLE_RE.sub("", line))


def _bullets(items) -> str:
    return "\n".join(f"- {item}" for item in items)


def render_prd(doc: dict, brief: Dict[str, str], mhash: str, pending=(), owner_role: str = OWNER_ROLE,
               registro: bool = False, author: str = "", today: Optional[date] = None) -> str:
    plan = doc["plan"]
    values = {"title": plan["title"], "prd_status": "Borrador"}
    if registro:
        closing = [item for epic in doc["epics"] for item in epic["done_when"]]
        values.update({"objective": brief["Goal"], "expected_outcome": "; ".join(closing),
                       "problem": brief["Problem"] or brief.get("Context", ""),
                       "context": brief.get("Context", "") or brief["Problem"],
                       "quarter_year": _quarter(today or date.today()), "author": author})
        values = {k: v for k, v in values.items() if v}
    if plan.get("mode") in INITIATIVE_TYPE:
        values["initiative_type"] = INITIATIVE_TYPE[plan["mode"]]
    if brief["Goal"].strip():
        values["executive_summary"] = brief["Goal"].strip()
    requirements = []
    for epic in doc["epics"]:
        requirements.append(f"**{epic['id']} — {epic['title']}**")
        requirements += [f"- {item}" for item in epic["done_when"]]
        requirements += [f"- {t['id']} {t['title']}: " + "; ".join(t["acceptance"]) for t in epic["tasks"] if t["acceptance"]]
    values["key_requirements"] = "\n".join(requirements)
    questions = _open_questions(brief, pending, owner_role)
    if questions:
        values["open_questions"] = questions
    text = _sub(pbtemplate.load("prd"), values)
    text = _rows(text, "in_scope", [{"name": f"{e['id']}: {e['title']}", "description": "; ".join(e["done_when"]) or e["title"]}
                                    for e in doc["epics"]])
    text = _rows(text, "out_scope", [{"name": item} for item in _items(brief["Non-goals"])])
    if registro:
        text = _rows(text, "nfr", [{"category": "Restricción", "requirement": c} for c in _items(brief["Constraints"])])
        text = _registro(text, "prd")
    return _pb(_header(mhash, "wow pack prd") + "\n" + text)


def render_rfc(doc: dict, brief: Dict[str, str], mhash: str, pending=(), owner_role: str = OWNER_ROLE,
               registro: bool = False, author: str = "") -> str:
    plan = doc["plan"]
    values = {"title": plan["title"], "status": "Borrador", "version": "0.1"}
    if registro:
        closing = [item for epic in doc["epics"] for item in epic["done_when"]]
        values.update({"rfc_id": plan["id"], "authors": author,
                       "problem_definition": brief["Problem"] or brief.get("Context", ""),
                       "business_impact": "; ".join(closing), "security": "; ".join(_items(brief["Constraints"])),
                       "alternatives": _bullets(f"Decidido: {_DECISION_ID_RE.sub('', d)}"
                                                for d in _items(brief["Decisions"]))})
        values = {k: v for k, v in values.items() if v}
    if brief["Goal"].strip():
        values["executive_summary"] = brief["Goal"].strip()
    if plan.get("mode") == "greenfield":
        values["coexistence_strategy"] = "No aplica: sistema nuevo; no convive con un sistema previo."
    questions = _open_questions(brief, pending, owner_role)
    if questions:
        values["open_questions"] = questions
    text = _sub(pbtemplate.load("rfc"), values)
    text = _rows(text, "goal", [{"": item} for epic in doc["epics"] for item in epic["done_when"]])
    text = _rows(text, "non_goal", [{"": item} for item in _items(brief["Non-goals"])])
    milestones = []
    for epic in doc["epics"]:
        estimates = [t["estimate"] for t in epic["tasks"]]
        eta = f"{sum(estimates)} story points" if all(e is not None for e in estimates) else ""
        milestones.append({"phase": epic["id"], "deliverable": epic["title"], "eta": eta})
    text = _rows(text, "milestone", milestones)
    if registro:
        tasks = [t for epic in doc["epics"] for t in epic["tasks"]]
        components = sorted({t["component"] for t in tasks if t.get("component")})
        text = _rows(text, "component", [{"name": c, "responsibility": "; ".join(t["title"] for t in tasks
                                                                                  if t.get("component") == c)}
                                         for c in components])
        text = _registro(text, "rfc")
    return _pb(_header(mhash, "wow pack rfc") + "\n" + text)


def _ph(key: str) -> str:
    return "{{" + key + "}}"


def render_epic(doc: dict, epic_id: str, mhash: str) -> str:
    epic = next((e for e in doc["epics"] if e["id"] == epic_id), None)
    if epic is None:
        raise ValueError(f"epic {epic_id} not found in the manifest")
    product = dict(epic.get("product") or {})
    key = doc["plan"]["export"]["epics"].get(epic_id)
    tasks = epic["tasks"]
    stories = {t["id"]: f"US-{n:03d}" for n, t in enumerate(tasks, 1)}
    status = "draft" if epic.get("status") == "draft" else "todo"
    scalar = {"epic_name": epic["title"], "status": status, "estimation_method": "story_points"}
    if key:
        scalar["jira_prefix"] = key.split("-")[0]
    if "big_move" in product:
        scalar["big_move"] = "Sí" if product["big_move"] else "No"
    for field, _ in pbcompletion.EPIC_FIELDS:
        if field in product and field != "big_move":
            scalar[field] = product[field]
    closing = "Criterios de cierre de la épica: " + "; ".join(epic["done_when"]) if epic["done_when"] else ""
    scalar["notes"] = " ".join(p for p in (product.get("notes", ""), closing) if p) or _ph("notes")
    lists = {field: list(product.get(field) or []) for field, _ in pbcompletion.EPIC_LISTS}
    lists["labels"] = lists["labels"] or sorted({l for t in tasks for l in t["labels"]})
    lists["components"] = lists["components"] or sorted({t["component"] for t in tasks if t.get("component")})
    lines = [_header(mhash, f"wow pack epic --id {epic_id}"), f"# Épica {epic_id} — {epic['title']}", "",
             "## Datos de la épica", "| Campo | Valor |", "| --- | --- |"]
    lines += [f"| {label} ({field}) | {_cell(scalar[field]) if scalar.get(field) else _ph(field)} |"
              for field, label in pbcompletion.EPIC_FIELDS]
    for field, label in pbcompletion.EPIC_LISTS:
        lines += ["", f"### {label} ({field})"] + ([f"- {_list_item(v)}" for v in lists[field]] or [f"- {_ph(field)}"])
    lines += ["", "## Historias"]
    for task in tasks:
        story = dict(task.get("story") or {})
        component = task.get("component") or _ph("component")
        values = {"story_points": str(task["estimate"]) if task["estimate"] is not None else "",
                  "priority": PRIORITY_ES.get(task["priority"] or "", ""), "component": task.get("component", ""),
                  "status": "todo"}
        values.update({k: v for k, v in story.items() if isinstance(v, str)})
        lines += ["", f"### {stories[task['id']]} — [{component}] {task['title']}",
                  "| Campo | Valor |", "| --- | --- |"]
        lines += [f"| {label} ({field}) | {_cell(values[field]) if values.get(field) else _ph(field)} |"
                  for field, label in pbcompletion.STORY_FIELDS]
        story_lists = {k: list(story.get(k) or []) for k in ("assumptions", "business_rules", "edge_cases", "assets")}
        story_lists["dependencies"] = [stories[d] if d in stories else f"{d} (otra épica)"
                                       for d in task["depends_on"]] or ["Ninguna"]
        story_lists["acceptance_criteria"] = [a.replace(": ", " — ", 1) for a in task["acceptance"]]
        story_lists["definition_of_ready"] = list(pbcompletion.DOR)
        story_lists["definition_of_done"] = [f"{c} — no" for c in pbcompletion.DOD]
        story_lists["tasks"] = []
        for sub in task["subtasks"]:
            sub = {"title": sub} if isinstance(sub, str) else sub
            story_lists["tasks"].append(
                f"{sub['title']} — Propósito: {sub.get('purpose') or _ph('purpose')} — Cómo: {sub.get('how_to') or _ph('how_to')}"
                f" — Componente: {sub.get('component') or component} — Estado: todo")
        for field, label in pbcompletion.STORY_LISTS:
            fixed = field in ("definition_of_ready", "definition_of_done")  # Product Brain's own text, commas included
            item = _cell if fixed else _list_item
            lines += ["", f"#### {label} ({field})"] + ([f"- {item(v)}" for v in story_lists[field]] or [f"- {_ph(field)}"])
    lines.append("")
    return _pb("\n".join(lines))


def parse_brief(text: str) -> Dict[str, str]:
    brief = {key: "" for key in _BRIEF_KEYS}
    section, context = "", []
    for line in text.splitlines():
        if line.startswith("## "):
            section = line.strip().lower()[3:]
            continue
        if section == "contexto" and line.strip():
            context.append(line.strip())
        match = _BULLET_RE.match(line) if section == "brief" else None
        if match and match.group(1).strip() in brief:
            brief[match.group(1).strip()] = match.group(2).strip()
    brief["Context"] = " ".join(context)
    return brief


def write_packet(project: Path, name: str, text: str, force: bool = False) -> Path:
    path = project / "wow" / "pb" / f"{name}.md"
    if path.exists() and not force:
        raise FileExistsError(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def ensure_preamble(project: Path) -> Path:
    path = project / "wow" / "pb" / "preamble.md"
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(PREAMBLE, encoding="utf-8")
    return path
